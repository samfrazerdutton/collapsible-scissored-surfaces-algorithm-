#!/usr/bin/env python3
"""Regenerates the GPS-trajectory half of REAL_GEO_BENCHMARK.md.

Real data: one continuous real single-trip GPS log (14,186 points) from
Microsoft Research's public Geolife Trajectories 1.3 dataset
(https://www.microsoft.com/en-us/download/details.aspx?id=52367), user 000,
file 20090403011657.plt. Not included in this repo (313MB zip for the full
182-user dataset) -- download it and extract that one file to
bench/_thirdparty/geolife_user000/Geolife Trajectories 1.3/Data/000/Trajectory/
before running this script, or point GEOLIFE_PLT at any other .plt file.

The LiDAR-vs-LASzip half of REAL_GEO_BENCHMARK.md is NOT regenerated by this
script: it depends on building the third-party LASzip library (git clone +
cmake -DLASZIP_DYN_LINK=1 -DLASZIP_SOURCE=1) and a small custom C API driver
(laz_geo_tool.cpp) against it, plus fetching a real LiDAR file from PDAL's
git+LFS test-data repo (autzen/stadium-utm.laz). See REAL_GEO_BENCHMARK.md's
"Regenerating these numbers" section for the exact one-time setup steps.
"""
import gzip
import bz2
import lzma
import os
import struct
import subprocess
import sys

try:
    import zstandard
    HAVE_ZSTD = True
except ImportError:
    HAVE_ZSTD = False

try:
    import brotli
    HAVE_BROTLI = True
except ImportError:
    HAVE_BROTLI = False

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)
SCISSORC = os.path.join(REPO_ROOT, "build", "scissorc.exe" if os.name == "nt" else "scissorc")
GEOLIFE_PLT = os.environ.get(
    "GEOLIFE_PLT",
    os.path.join(HERE, "_thirdparty", "geolife_user000", "Geolife Trajectories 1.3",
                 "Data", "000", "Trajectory", "20090403011657.plt"),
)
SCALE = 1_000_000  # preserve all 6 decimal digits of lat/lon exactly -- lossless


def encode_polyline(coords, precision=1e5):
    """Google's Encoded Polyline Algorithm Format (the real production
    encoding Google Maps/Mapbox/OSRM use for compact polyline transport)."""
    result = []
    prev_lat = prev_lon = 0
    for lat, lon in coords:
        lat_i = round(lat * precision)
        lon_i = round(lon * precision)
        for v, prev in ((lat_i, prev_lat), (lon_i, prev_lon)):
            d = v - prev
            d = ~(d << 1) if d < 0 else (d << 1)
            while d >= 0x20:
                result.append(chr((0x20 | (d & 0x1f)) + 63))
                d >>= 5
            result.append(chr(d + 63))
        prev_lat, prev_lon = lat_i, lon_i
    return ''.join(result)


def decode_polyline(s, precision=1e5):
    coords = []
    index = lat = lon = 0
    n = len(s)
    while index < n:
        for is_lat in (True, False):
            shift = result = 0
            while True:
                b = ord(s[index]) - 63
                index += 1
                result |= (b & 0x1f) << shift
                shift += 5
                if b < 0x20:
                    break
            d = (~(result >> 1)) if (result & 1) else (result >> 1)
            if is_lat:
                lat += d
            else:
                lon += d
        coords.append((lat / precision, lon / precision))
    return coords


def main():
    if not os.path.exists(GEOLIFE_PLT):
        print(f"Geolife .plt file not found at {GEOLIFE_PLT}", file=sys.stderr)
        print("Download Geolife Trajectories 1.3 and extract user 000's trajectory, "
              "or set GEOLIFE_PLT to any .plt file.", file=sys.stderr)
        return 1
    if not os.path.exists(SCISSORC):
        print(f"scissorc not found at {SCISSORC} -- build it first (cmake --build build)", file=sys.stderr)
        return 1

    with open(GEOLIFE_PLT) as f:
        lines = f.readlines()[6:]  # Geolife's fixed 6-line header
    pts = []
    for line in lines:
        parts = line.strip().split(',')
        pts.append((float(parts[0]), float(parts[1])))
    print(f"points: {len(pts)} (real GPS trajectory: {GEOLIFE_PLT})")

    work = os.path.join(HERE, "_tmp_geo_bench")
    os.makedirs(work, exist_ok=True)
    xy_path = os.path.join(work, "gps_xy.txt")
    with open(xy_path, "w") as f:
        for lat, lon in pts:
            f.write(f"{lat} {lon}\n")

    packed = b''.join(struct.pack('<ii', round(lat * SCALE), round(lon * SCALE)) for lat, lon in pts)
    raw_packed_size = len(packed)
    print(f"raw packed (4-byte int/axis): {raw_packed_size} bytes")

    codecs = [
        ("gzip -9", gzip.compress(packed, compresslevel=9)),
        ("bz2 -9", bz2.compress(packed, compresslevel=9)),
        ("lzma -9", lzma.compress(packed, preset=9)),
    ]
    if HAVE_ZSTD:
        codecs.append(("zstd -19", zstandard.ZstdCompressor(level=19).compress(packed)))
    if HAVE_BROTLI:
        codecs.append(("brotli -11", brotli.compress(packed, quality=11)))
    for name, comp in codecs:
        pct = 100.0 * (1 - len(comp) / raw_packed_size)
        print(f"{name}: {len(comp)} bytes ({pct:.1f}% smaller than raw packed)")

    polyline = encode_polyline(pts)
    polyline_bytes = len(polyline.encode('ascii'))
    pct = 100.0 * (1 - polyline_bytes / raw_packed_size)
    decoded = decode_polyline(polyline)
    max_err_deg = max(max(abs(a[0] - b[0]), abs(a[1] - b[1])) for a, b in zip(pts, decoded))
    print(f"Google Encoded Polyline (1e5 precision): {polyline_bytes} bytes ({pct:.1f}% smaller) "
          f"-- lossy by design, max error {max_err_deg:.7f} deg (~{max_err_deg*111000:.2f} m)")

    csa_out = os.path.join(work, "gps_csa.csa")
    r = subprocess.run([SCISSORC, "compress-geo2d", xy_path, csa_out, "--scale", str(SCALE)],
                        capture_output=True, text=True)
    print(r.stdout.strip())
    if r.returncode != 0:
        print(r.stderr, file=sys.stderr)
        return 1
    csa_size = os.path.getsize(csa_out)
    pct = 100.0 * (1 - csa_size / raw_packed_size)

    csa_decoded = os.path.join(work, "gps_csa_decoded.xy")
    r = subprocess.run([SCISSORC, "decompress-geo2d", csa_out, csa_decoded], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stderr, file=sys.stderr)
        return 1
    with open(csa_decoded) as f:
        back = [tuple(float(v) for v in line.split()) for line in f]
    round_trip_ok = len(back) == len(pts) and all(
        abs(a[0] - b[0]) < 1e-9 and abs(a[1] - b[1]) < 1e-9 for a, b in zip(pts, back)
    )
    print(f"CSA compress-geo2d: {csa_size} bytes ({pct:.1f}% smaller than raw packed), "
          f"round-trip {'PASS (exact)' if round_trip_ok else 'FAIL'}")
    return 0 if round_trip_ok else 1


if __name__ == "__main__":
    sys.exit(main())
