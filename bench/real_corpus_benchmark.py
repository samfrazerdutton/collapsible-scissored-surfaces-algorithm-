#!/usr/bin/env python3
"""Benchmarks CSA against real market competitors on a real, non-synthetic
corpus: concatenated C++ source files from a large local repository
(OpenFHE), not text generated to flatter any particular compressor. This
is the credibility check that BENCHMARKS.md's synthetic datasets and
USE_CASES.md's realistic-but-generated datasets can't fully provide --
any claim to be "a real competitor" has to survive contact with data
nobody wrote for this purpose, and has to be measured against what
"the market" actually uses today, not just the textbook trio of
gzip/bz2/lzma. zstd in particular is what most production systems mean
by "modern compression" now (Meta/Facebook; used by the Linux kernel,
Debian, Btrfs, etc.), and brotli is the modern web-content-compression
default (Chrome, Firefox, most CDNs) -- both are included alongside
gzip/bz2/lzma for that reason.

Runs all three of CSA's speed/ratio levels (fast/balanced/high) -- the
same tradeoff every production LZ compressor exposes (gzip -1..-9, zstd
-1..-22) -- since "is it good" depends on which point on that curve you
need.

Writes REAL_CORPUS_BENCHMARK.md from a real measurement on this run.
"""
import bz2
import lzma
import os
import subprocess
import sys
import time
import zlib

try:
    import zstandard
    HAVE_ZSTD = True
except ImportError:
    HAVE_ZSTD = False

try:
    import brotli
    HAVE_BROTLI = True
except ImportError:
    HAVE_BROTLI = False

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCISSORC = os.path.join(ROOT, "build", "scissorc.exe")
CORPUS = os.path.join(ROOT, "bench", "datasets_real", "source_corpus.bin")
TMP = os.path.join(ROOT, "bench", "_tmp")
os.makedirs(TMP, exist_ok=True)

MODE_NAMES = {0: "Raw", 1: "Pantograph Lift", 2: "Geo2D", 3: "Geo3D", 4: "LZ dictionary matcher", 5: "BWT + move-to-front"}
LEVELS = ["fast", "balanced", "high"]


def run(*args):
    r = subprocess.run([SCISSORC, *args], capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"scissorc {args} failed: {r.stderr}")
    return r.stdout


def csa_at_level(data, level):
    out_c = os.path.join(TMP, f"source_corpus_{level}.csa")
    out_d = os.path.join(TMP, f"source_corpus_{level}.dec")
    t0 = time.perf_counter()
    run("compress", CORPUS, out_c, "--level", level)
    compress_time = time.perf_counter() - t0

    t0 = time.perf_counter()
    run("decompress", out_c, out_d)
    decompress_time = time.perf_counter() - t0

    dec = open(out_d, "rb").read()
    ok = dec == data
    size = os.path.getsize(out_c)
    mode = MODE_NAMES.get(open(out_c, "rb").read(5)[4], "?")
    return {"level": level, "size": size, "compress_time": compress_time,
             "decompress_time": decompress_time, "ok": ok, "mode": mode}


def main():
    if not os.path.exists(SCISSORC):
        print(f"error: {SCISSORC} not found -- build the project first.", file=sys.stderr)
        sys.exit(1)
    if not os.path.exists(CORPUS):
        print(f"error: {CORPUS} not found -- run bench/build_real_corpus.py first.", file=sys.stderr)
        sys.exit(1)

    data = open(CORPUS, "rb").read()
    raw = len(data)

    results = [csa_at_level(data, lvl) for lvl in LEVELS]

    t0 = time.perf_counter()
    gzip_size = len(zlib.compress(data, 9))
    gzip_time = time.perf_counter() - t0

    t0 = time.perf_counter()
    bz2_size = len(bz2.compress(data, 9))
    bz2_time = time.perf_counter() - t0

    t0 = time.perf_counter()
    lzma_size = len(lzma.compress(data, preset=9))
    lzma_time = time.perf_counter() - t0

    zstd_results = []
    if HAVE_ZSTD:
        for level, label in [(3, "zstd -3 (default)"), (19, "zstd -19 (high)")]:
            t0 = time.perf_counter()
            size = len(zstandard.ZstdCompressor(level=level).compress(data))
            t = time.perf_counter() - t0
            zstd_results.append({"label": label, "size": size, "time": t})

    brotli_results = []
    if HAVE_BROTLI:
        for quality, label in [(5, "brotli -5 (default)"), (11, "brotli -11 (max)")]:
            t0 = time.perf_counter()
            size = len(brotli.compress(data, quality=quality))
            t = time.perf_counter() - t0
            brotli_results.append({"label": label, "size": size, "time": t})

    lines = []
    lines.append("# CSA vs. real market competitors on a real corpus\n")
    lines.append(
        "Generated by `bench/real_corpus_benchmark.py`. The corpus is "
        f"{raw:,} bytes of real, concatenated C++ source files from a large "
        "local repository (OpenFHE) -- not text written or generated for "
        "this benchmark, and not tuned to flatter any compressor. This is "
        "the credibility check `BENCHMARKS.md`'s synthetic shapes and "
        "`USE_CASES.md`'s realistic-but-generated scenarios can't fully "
        "provide. CSA is run at all three speed/ratio levels it exposes "
        "(`--level fast|balanced|high`), the same tradeoff every "
        "production LZ compressor exposes (gzip -1..-9, zstd -1..-22) -- "
        "\"is it good\" depends on which point on that curve you need.\n"
    )
    lines.append("| compressor | size | vs raw | compress time | round-trip |")
    lines.append("|---|---:|---:|---:|:---:|")
    for r in results:
        lines.append(
            f"| CSA --level {r['level']} ({r['mode']}) | {r['size']:,} | "
            f"{100*(1-r['size']/raw):.1f}% smaller | {r['compress_time']:.2f}s | "
            f"{'PASS' if r['ok'] else 'FAIL'} |"
        )
    lines.append(f"| gzip -9 | {gzip_size:,} | {100*(1-gzip_size/raw):.1f}% smaller | {gzip_time:.2f}s | (reference) |")
    lines.append(f"| bz2 -9 | {bz2_size:,} | {100*(1-bz2_size/raw):.1f}% smaller | {bz2_time:.2f}s | (reference) |")
    lines.append(f"| lzma -9 | {lzma_size:,} | {100*(1-lzma_size/raw):.1f}% smaller | {lzma_time:.2f}s | (reference) |")
    for zr in zstd_results:
        lines.append(f"| {zr['label']} | {zr['size']:,} | {100*(1-zr['size']/raw):.1f}% smaller | {zr['time']:.2f}s | (reference) |")
    for br in brotli_results:
        lines.append(f"| {br['label']} | {br['size']:,} | {100*(1-br['size']/raw):.1f}% smaller | {br['time']:.2f}s | (reference) |")
    if not HAVE_ZSTD:
        lines.append("| zstd | -- | (zstandard package not installed) | -- | -- |")
    if not HAVE_BROTLI:
        lines.append("| brotli | -- | (brotli package not installed) | -- | -- |")
    lines.append("")
    lines.append(f"CSA decompress time (all levels, same format): ~{results[0]['decompress_time']:.2f}s\n")

    all_refs = {"gzip -9": gzip_size, "bz2 -9": bz2_size, "lzma -9": lzma_size}
    all_refs.update({zr["label"]: zr["size"] for zr in zstd_results})
    all_refs.update({br["label"]: br["size"] for br in brotli_results})
    best_ref_label = min(all_refs, key=all_refs.get)
    best_ref = all_refs[best_ref_label]
    lines.append("## Honest verdict\n")
    beats = [r for r in results if r["size"] < best_ref]
    faster_than_lzma = [r for r in results if r["compress_time"] < lzma_time]
    if beats:
        lines.append(
            f"- At `--level {beats[-1]['level']}`, CSA beats the best of every reference compressor "
            f"here (including {best_ref_label}) outright ({beats[-1]['size']:,} vs {best_ref:,} bytes).\n"
        )
    else:
        gap_pct = 100 * (results[-1]["size"] - best_ref) / best_ref
        lines.append(
            f"- Even at `--level high`, CSA does not beat the best reference here ({best_ref_label}): "
            f"{results[-1]['size']:,} bytes vs {best_ref:,} bytes ({gap_pct:.1f}% larger). Real source "
            "code has exactly the kind of medium-range, high-order repeated structure (identifiers, "
            "indentation, common phrases) that LZMA/zstd's optimal-ish parsing and larger match "
            "finders, and bz2's Burrows-Wheeler Transform, are specifically built to exploit, and this "
            "codec's lazy-matching LZ + order-1 entropy model currently isn't. (CSA's BWT mode, which "
            "wins big on smaller realistic files -- see USE_CASES.md -- is genuinely tried here too, "
            "not skipped: it's cheap enough since switching to a linear-time suffix-array construction "
            "(see DESIGN.md) to run unconditionally at this size, but it still doesn't win on real "
            "source code specifically -- LZ's exact-repeat matching simply covers this corpus's "
            "redundancy better.) A real, carefully-implemented DP-based optimal-parsing pass was "
            "actually built and measured against this exact corpus -- and reverted, because it never "
            "won: byte-identical output to the plain lazy parse at 2.4x the compress time (see "
            "DESIGN.md's \"Optimal (cost-based) LZ parsing\" section for the full postmortem, including "
            "a real ~13x performance bug found and fixed along the way before that measurement was even "
            "possible). So closing this gap isn't a matter of adding optimal parsing -- that specific "
            "idea was tried and didn't pay off. What's actually missing is a cost model with some "
            "source of information genuinely independent of the parse it's evaluating (e.g. real "
            "simulated adaptive-coder state, not a static proxy derived from the lazy parser's own "
            "output statistics), which remains open future work, not a known fix waiting to be applied.\n"
        )
    if faster_than_lzma:
        fastest_beating_gzip_and_bz2 = next(
            (r for r in results if r["size"] < gzip_size and r["size"] < bz2_size), None
        )
        if fastest_beating_gzip_and_bz2:
            lines.append(
                f"- At `--level {fastest_beating_gzip_and_bz2['level']}`, CSA beats both gzip and bz2 "
                f"on size ({fastest_beating_gzip_and_bz2['size']:,} bytes) while compressing faster "
                f"than lzma ({fastest_beating_gzip_and_bz2['compress_time']:.2f}s vs {lzma_time:.2f}s) "
                "-- a real, honest position on the speed/ratio curve, not a win on every axis at "
                "once.\n"
            )
    if zstd_results:
        zstd_fast = zstd_results[0]
        beats_zstd_fast = [r for r in results if r["size"] < zstd_fast["size"]]
        if beats_zstd_fast:
            lines.append(
                f"- CSA `--level {beats_zstd_fast[0]['level']}` beats {zstd_fast['label']} on size "
                f"({beats_zstd_fast[0]['size']:,} vs {zstd_fast['size']:,} bytes) -- but {zstd_fast['label']} "
                f"did it in {zstd_fast['time']:.2f}s (CSA took {beats_zstd_fast[0]['compress_time']:.2f}s "
                f"at that level). zstd's default level alone compresses this whole 18MB corpus in a "
                "fraction of a second; matching its ratio is the easy part.\n"
            )
        if len(zstd_results) > 1:
            zstd_high = zstd_results[1]
            csa_best = results[-1]
            if zstd_high["size"] <= csa_best["size"]:
                gap = 100 * (csa_best["size"] - zstd_high["size"]) / zstd_high["size"]
                speed_ratio = csa_best["compress_time"] / zstd_high["time"]
                lines.append(
                    f"- The more important comparison: **{zstd_high['label']} beats CSA `--level high` "
                    f"on both size and speed at once** ({zstd_high['size']:,} vs {csa_best['size']:,} "
                    f"bytes, {gap:.1f}% smaller, in {zstd_high['time']:.2f}s vs CSA's "
                    f"{csa_best['compress_time']:.2f}s -- {speed_ratio:.1f}x faster). That's the honest "
                    "measure of the actual gap to a modern production compressor: not just ratio, but "
                    "the whole speed/ratio curve simultaneously. Closing it needs a smarter match finder "
                    "and a genuinely independent cost model for parse decisions (optimal-parsing itself "
                    "was tried and reverted -- see the postmortem above), plus real performance "
                    "engineering zstd has had years of -- not a claim this project makes.\n"
                )

    out_path = os.path.join(ROOT, "REAL_CORPUS_BENCHMARK.md")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}")
    if not all(r["ok"] for r in results):
        print("ERROR: at least one round-trip failed", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
